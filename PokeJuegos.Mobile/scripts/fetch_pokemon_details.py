#!/usr/bin/env python3
"""Downloads the base data for the pokemon listed in Resources/Raw/pokemon_list.json
from the PokeAPI and consolidates it into Resources/Raw/pokemon_details.json (bundled
as a MauiAsset).

Covers generations I-III (national dex #1-386). Resources/Raw/pokemon_list.json is
generated by scripts/fetch_pokemon_list.py; run that first if it doesn't
exist yet or if the generation range needs to change.

Run once, by hand; it's not part of the app's normal build flow (dotnet
build). Only requires Python 3 (stdlib, no external dependencies).
If a new Pokemon generation gets added, re-run fetch_pokemon_list.py with
an updated limit, then run this script again.

Usage:
    python3 scripts/fetch_pokemon_list.py   # once, or when the range changes
    python3 scripts/fetch_pokemon_details.py
"""
import json
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST_FILE = ROOT / "Resources" / "Raw" / "pokemon_list.json"
OUTPUT_FILE = ROOT / "Resources" / "Raw" / "pokemon_details.json"
API_BASE = "https://pokeapi.co/api/v2/pokemon"
REQUEST_DELAY_SECONDS = 0.2


def fetch_pokemon(name: str, retries: int = 3) -> dict:
    url = f"{API_BASE}/{name}"
    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": "Mozilla/5.0 (compatible; poke-juegos-data-fetch/1.0)",
            "Accept": "application/json",
        },
    )
    last_error = None
    for attempt in range(retries):
        try:
            with urllib.request.urlopen(request, timeout=15) as response:
                return json.loads(response.read())
        except (urllib.error.URLError, urllib.error.HTTPError) as error:
            last_error = error
            if attempt < retries - 1:
                time.sleep(1 * (attempt + 1))  # backoff simple: 1s, 2s, ...
    raise last_error


def get_generation(pokemon_id: int) -> int:
    """Gen I-III only, since Resources/Raw/pokemon_list.json is capped at #386."""
    if pokemon_id <= 151:
        return 1
    if pokemon_id <= 251:
        return 2
    return 3


def to_pokemon_detail(raw: dict) -> dict:
    artwork = raw["sprites"]["other"]["official-artwork"]
    return {
        "id": raw["id"],
        "name": raw["name"],
        "generation": get_generation(raw["id"]),
        "weight": raw["weight"],
        "height": raw["height"],
        "types": raw["types"],
        "sprites": {
            "other": {
                "official-artwork": {
                    "front_default": artwork.get("front_default"),
                    "front_shiny": artwork.get("front_shiny"),
                },
            },
        },
    }


def main() -> None:
    names = [entry["name"] for entry in json.loads(LIST_FILE.read_text())["results"]]
    total = len(names)
    print(f"Downloading {total} pokemon from {API_BASE}...")

    pokemon_data = []
    failed = []
    for i, name in enumerate(names, start=1):
        try:
            raw = fetch_pokemon(name)
        except (urllib.error.URLError, urllib.error.HTTPError) as error:
            print(f"  [{i}/{total}] ERROR with '{name}': {error}")
            failed.append(name)
            continue

        pokemon_data.append(to_pokemon_detail(raw))
        print(f"  [{i}/{total}] {name} ok")
        time.sleep(REQUEST_DELAY_SECONDS)

    pokemon_data.sort(key=lambda p: p["id"])
    OUTPUT_FILE.write_text(json.dumps(pokemon_data, indent=2, ensure_ascii=False) + "\n")

    print(f"\nDone: {OUTPUT_FILE} ({len(pokemon_data)}/{total} pokemon)")
    if failed:
        print(f"Failed {len(failed)}: {', '.join(failed)}")


if __name__ == "__main__":
    main()
